def strs(values):
    return "PackedStringArray(%s)" % ", ".join('"%s"' % v for v in values)


def main():
    import importlib.util
    path = os.path.join(os.path.dirname(__file__), "recipes_more.py")
    if os.path.exists(path):
        spec = importlib.util.spec_from_file_location("recipes_more", path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        R.extend(mod.R)
    os.makedirs(OUT, exist_ok=True)
    for r in R:
        cond = r["cond"]
        lines = [
            'script = ExtResource("1_recipe")',
            'recipe_id = &"%s"' % r["id"],
            'title = "%s"' % r["title"],
            "category = %d" % r["cat"],
            'formula = "%s"' % r["formula"],
            'description = "%s"' % r["desc"],
            'riddle = "%s"' % r.get("riddle", ""),
            "ingredients = %s" % strs(r["ingredients"]),
            "method_steps = %s" % strs(r["steps"]),
            "condition_traits = %s" % strs(cond.keys()),
            "condition_min = PackedFloat32Array(%s)" % ", ".join("%g" % v[0] for v in cond.values()),
            "condition_max = PackedFloat32Array(%s)" % ", ".join("%g" % v[1] for v in cond.values()),
        ]
        text = ('[gd_resource type="Resource" script_class="RecipeData" load_steps=2 format=3]\n\n'
                '[ext_resource type="Script" path="res://world_3d/grimoire_system/recipe_data.gd" id="1_recipe"]\n\n'
                "[resource]\n%s\n" % "\n".join(lines))
        with open(os.path.join(OUT, r["id"] + ".tres"), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("wrote", len(R), "recipes")


main()
